const STORAGE_KEY = "groundup_construction_calendar_tasks_v1";

export function getStoredConstructionTasks(projectId: string): ConstructionTask[] {
  if (typeof window === "undefined") return INITIAL_CONSTRUCTION_TASKS;
  try {
    const raw = window.localStorage.getItem(`${STORAGE_KEY}_${projectId}`);
    if (!raw) {
      // Also check general key
      const general = window.localStorage.getItem(STORAGE_KEY);
      if (general) return JSON.parse(general);
      return INITIAL_CONSTRUCTION_TASKS;
    }
    return JSON.parse(raw);
  } catch {
    return INITIAL_CONSTRUCTION_TASKS;
  }
}

export function saveStoredConstructionTasks(projectId: string, tasks: ConstructionTask[]): void {
  if (typeof window === "undefined") return;
  try {
    window.localStorage.setItem(`${STORAGE_KEY}_${projectId}`, JSON.stringify(tasks));
    window.localStorage.setItem(STORAGE_KEY, JSON.stringify(tasks));
  } catch (err) {
    console.error("Failed to save construction tasks:", err);
  }
}
